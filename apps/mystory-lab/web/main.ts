interface Frame {
  screen: Screen;
  records: { seq: number; source: string; kind: string; text: string | null; data: unknown }[];
  calls: ModelCall[];
}

/**
 * The conversation, as a thread.
 *
 * It accumulates rather than being replaced. A young person is being asked to
 * recognise a retelling of what they said as theirs, and a screen that has
 * thrown away everything they said is a poor place to ask that. Each turn
 * appends: what the bot asked, what they answered, in order, scrolling.
 *
 * The stage controls live under the thread rather than inside it, because
 * choosing between three write-ups, dragging a slider and editing a paragraph
 * are not messages — they are things done to what the messages produced.
 */
type Who = "them" | "me" | "system";

/**
 * A message.
 *
 * No avatar. A one-to-one WhatsApp chat shows none beside the bubbles — only
 * the header says who you are talking to — which is both what the real thing
 * looks like and the cleanest answer to not wanting to put a face on a young
 * person who has not given us one.
 *
 * The time and, on their own messages, the ticks live INSIDE the bubble and
 * are floated, so a short message sits on one line with the time beside it and
 * a long one wraps above it. That float is the whole trick to why WhatsApp
 * bubbles look the way they do.
 */
const TICKS = `<span class="ticks" aria-hidden="true"><svg viewBox="0 0 16 11">
    <path d="M11.07.65a.5.5 0 0 0-.71.02L5.2 6.2 3.3 4.2a.5.5 0 1 0-.72.7l2.26 2.38a.5.5 0 0 0 .72 0l5.53-5.92a.5.5 0 0 0-.02-.71Z"/>
    <path d="M15.07.65a.5.5 0 0 0-.71.02L9.2 6.2 8.6 5.56l-.7.75.94.99a.5.5 0 0 0 .72 0l5.53-5.92a.5.5 0 0 0-.02-.73Z"/>
  </svg></span>`;

/** hh:mm, as a chat shows it. */
const clock = (at?: string): string => {
  const d = at ? new Date(at) : new Date();
  return `${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
};

const bubble = (who: Who, html: string, at?: string): string =>
  who === "system"
    ? `<div class="msg system-msg turn"><div class="bubble system">${html}</div></div>`
    : `<div class="msg from-${who}">
         <div class="bubble">${html}<span class="meta">${clock(at)}${who === "me" ? TICKS : ""}</span></div>
       </div>`;

/**
 * Everything said so far, rebuilt from the records.
 *
 * The records are the source, not a parallel list the UI keeps: what appears
 * in the thread is exactly what was stored, which is the point of a lab whose
 * job is to show what would be stored.
 *
 * Not everything stored is a message, though. The three retellings are each
 * recorded as shown, because they were — but they are shown as cards to
 * choose between, and repeating them as chat bubbles above the cards says the
 * same thing twice.
 */
function threadFrom(records: Frame["records"]): string {
  const parts: string[] = [];
  /** The record each bubble came from, so voice notes can be re-seated. */
  const seqs: number[] = [];
  const push = (html: string, seq: number) => {
    parts.push(html);
    seqs.push(seq);
  };
  for (const r of records) {
    const data = (r.data ?? {}) as Record<string, unknown>;

    if (r.kind === "request_shown" || r.kind === "clarification_request") {
      if (r.text) push(bubble("them", escapeHtml(r.text)), r.seq);
    } else if (r.kind === "model_shown") {
      // A candidate retelling: it belongs in the cards, not in the thread.
      if (typeof data["index"] === "number") continue;
      if (r.text) push(bubble("them", escapeHtml(r.text)), r.seq);
    } else if (r.kind === "participant_original" || r.kind === "participant_clarification") {
      if (r.text) push(bubble("me", escapeHtml(r.text)), r.seq);
    } else if (r.kind === "participant_correction") {
      if (r.text) push(bubble("me", escapeHtml(r.text)), r.seq);
    } else if (r.kind === "participant_reaction" && typeof data["persona"] === "string") {
      // Which one they picked, said as a person would say it. The retelling
      // itself is on screen; repeating it here is noise.
      push(bubble("me", `I&rsquo;ll take the <em>${escapeHtml(data["persona"])}</em> one.`), r.seq);
    } else if (r.kind === "participant_rating") {
      push(bubble("me", `${escapeHtml(data["rating"])} out of ${escapeHtml(data["max"])}`), r.seq);
    } else if (r.kind === "participant_edit") {
      push(bubble("system", "They rewrote the write-up in their own words."), r.seq);
    } else if (r.kind === "participant_reaction" && typeof data["restored"] === "string") {
      push(bubble("system", "They put the previous version back."), r.seq);
    } else if (r.kind === "fallback_applied" && typeof data["reason"] === "string" && !data["persona"]) {
      push(bubble("system", `The model could not be reached: ${escapeHtml(data["reason"])}.`), r.seq);
    }
  }
  /**
   * Mark the first bubble of each run.
   *
   * WhatsApp puts the tail on the first message a speaker sends and opens the
   * spacing there, so five bubbles from one side read as a single turn rather
   * than five interruptions. Applied here rather than while building, because
   * a record does not know what follows it.
   */
  return parts
    .map((html, i) => {
      const mine = html.includes("from-me");
      const firstOfRun = i === 0 || parts[i - 1]!.includes("from-me") !== mine;
      const marked = firstOfRun ? html.replace('class="msg ', 'class="msg turn ') : html;
      return marked.replace("<div class=\"msg", `<div data-seq="${seqs[i]}" class="msg`);
    })
    .join("");
}

function scrollThread(): void {
  const thread = $("thread");
  thread.scrollTop = thread.scrollHeight;
}

/** Wire whatever controls this stage put on screen. */
function wireStageControls(): void {
  /**
   * Press and hold a retelling to choose it.
   *
   * The gesture a young person already has for "this one" is holding a message
   * down and putting a thumb on it, so that is the gesture — and the thumb
   * lands on the bubble before the page moves on, because a choice that
   * vanishes the instant you make it does not feel like a choice.
   *
   * Tap and Enter do the same thing. Long-press is what the hint teaches, not
   * the only way in: nobody on a laptop, a keyboard or a switch should be
   * stranded at the one screen the whole method turns on.
   */
  for (const el of document.querySelectorAll<HTMLElement>(".choice-bubble:not([data-wired])")) {
    el.dataset["wired"] = "yes";
    let held: ReturnType<typeof setTimeout> | null = null;
    let fired = false;

    const choose = () => {
      if (busy) return;
      fired = true;
      el.classList.add("chosen");
      el.classList.remove("holding");
      // Long enough to see the thumb land, short enough not to feel stuck.
      setTimeout(() => void turn({ action: "submit", input: el.dataset["choice"] ?? "" }), 320);
    };

    /**
     * A tap SELECTS. It does not choose.
     *
     * Tap used to be a full second way of choosing, on the reasoning that
     * long-press should be taught and not required. That was wrong in one
     * specific way: these bubbles are paragraphs, and the first thing anybody
     * does with a paragraph on a phone is touch it while reading. Somebody
     * tapped one to look at it and the study recorded their answer and moved
     * on — the single most consequential screen in the method, decided by
     * accident.
     *
     * So a tap highlights the one under your finger and puts a confirm button
     * up. Holding still chooses outright, because a press-and-hold is not
     * something anybody does by accident, and it is the gesture the hint
     * teaches. Keyboard and switch users get the same two steps as a tap.
     */
    const select = () => {
      if (busy || fired) return;
      for (const other of document.querySelectorAll(".choice-bubble")) other.classList.remove("picked");
      el.classList.add("picked");
      const confirm = document.getElementById("confirmChoice") as HTMLButtonElement | null;
      if (confirm) {
        confirm.hidden = false;
        confirm.dataset["choice"] = el.dataset["choice"] ?? "";
      }
      scrollThread();
    };
    const cancel = () => {
      if (held) clearTimeout(held);
      held = null;
      el.classList.remove("holding");
    };

    el.addEventListener("pointerdown", () => {
      if (fired) return;
      el.classList.add("holding");
      held = setTimeout(choose, 420);
    });
    el.addEventListener("pointerup", () => {
      const wasHolding = held !== null;
      cancel();
      // Released before the hold completed: that was a tap, so select it and
      // wait to be told rather than deciding for them.
      if (wasHolding && !fired) select();
    });
    el.addEventListener("pointerleave", cancel);
    el.addEventListener("pointercancel", cancel);
    // Holding a bubble on iOS otherwise raises the text-selection callout.
    el.addEventListener("contextmenu", (event) => event.preventDefault());
    el.addEventListener("keydown", (event) => {
      if (fired) return;
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        select();
      }
    });
  }

  const submit = () => {
    const picked = document.querySelector<HTMLInputElement>('input[name="choice"]:checked');
    const range = document.getElementById("ratingRange") as HTMLInputElement | null;
    // An untouched slider is not an answer. Belt as well as braces: the button
    // is disabled too, and both have to fail for a number nobody chose to be
    // recorded as though they had.
    if (range && range.dataset["set"] !== "yes") return;
    // `echo` only when the value is something they wrote. A choice sends an
    // index and a rating sends a number, and neither is a sentence anybody
    // said — the thread renders those as "I'll take the plain one" and
    // "7 out of 10" once recorded, which is what should appear.
    void turn({ action: "submit", input: picked?.value ?? range?.value ?? "", echo: false });
  };

  /**
   * The confirm, wired once.
   *
   * This function runs again as each retelling lands, and the button is the
   * same element every time — a second listener on it would submit the choice
   * twice, which at this stage means recording two answers to the question the
   * whole method turns on.
   */
  const confirm = document.getElementById("confirmChoice") as HTMLButtonElement | null;
  if (confirm && !confirm.dataset["wired"]) {
    confirm.dataset["wired"] = "yes";
    confirm.addEventListener("click", () => {
      const index = confirm.dataset["choice"];
      if (index === undefined || index === "" || busy) return;
      document.querySelector<HTMLElement>(`.choice-bubble[data-choice="${index}"]`)?.classList.add("chosen");
      confirm.disabled = true;
      // Long enough to see the thumb land, as the hold gesture does.
      setTimeout(() => void turn({ action: "submit", input: index }), 320);
    });
  }

  document.getElementById("send")?.addEventListener("click", submit);
  document.getElementById("cont")?.addEventListener("click", () => void turn({ action: "next" }));
  document.getElementById("skip")?.addEventListener("click", () => void turn({ action: "skip" }));
  document.getElementById("revert")?.addEventListener("click", () => void turn({ action: "revert" }));
  document.getElementById("keep")?.addEventListener("click", () => {
    const edited = (document.getElementById("scenarioEdit") as HTMLTextAreaElement | null)?.value ?? "";
    void turn({ action: "keep", input: edited });
  });

  // The rewrite request at the adapt stage. Its own box rather than the message
  // bar: "describe what to change" is an instruction about a text, not a reply
  // in the conversation, and it sits beside the text it is about.
  const rewrite = document.getElementById("rewrite") as HTMLTextAreaElement | null;
  const askRewrite = () => {
    const said = rewrite?.value ?? "";
    if (!said.trim()) return;
    if (rewrite) rewrite.value = "";
    void turn({ action: "submit", input: said, echo: true });
  };
  document.getElementById("sendRewrite")?.addEventListener("click", askRewrite);
  rewrite?.addEventListener("keydown", (e) => {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      askRewrite();
    }
  });

  // Cmd/Ctrl+Enter keeps an edited write-up, as the original does.
  /**
   * Grow the retelling box to whatever came out of the model.
   *
   * They are being asked to read it closely enough to say what is wrong with
   * it and then to edit it, and a fixed seven-row box showed a nine-line
   * paragraph through a letterbox. Sized to content on render and again on
   * every keystroke, so it never scrolls internally while there is room on the
   * page.
   */
  const grow = (el: HTMLTextAreaElement) => {
    el.style.height = "auto";
    el.style.height = `${el.scrollHeight}px`;
  };
  const edit = document.getElementById("scenarioEdit") as HTMLTextAreaElement | null;
  if (edit) {
    grow(edit);
    edit.addEventListener("input", () => grow(edit));
  }
  edit?.addEventListener("keydown", (e) => {
    if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      void turn({ action: "keep", input: edit.value });
    }
  });

  document.querySelectorAll<HTMLInputElement>('input[name="choice"]').forEach((radio) => {
    radio.addEventListener("change", () => {
      document.querySelectorAll(".card-choice").forEach((c) => c.classList.remove("picked"));
      radio.closest(".card-choice")?.classList.add("picked");
    });
  });

  const range = document.getElementById("ratingRange") as HTMLInputElement | null;
  if (range) {
    const send = document.getElementById("send") as HTMLButtonElement | null;
    if (send) {
      send.disabled = true;
      send.dataset["gate"] = "shut";
    }
    const touched = () => {
      range.dataset["set"] = "yes";
      const out = document.getElementById("ratingValue");
      if (out) out.textContent = `${range.value} out of ${range.max}`;
      if (send) {
        delete send.dataset["gate"];
        send.disabled = false;
      }
    };
    // `input` covers dragging; `keydown` covers the arrow keys, which move the
    // handle without firing on some browsers until release.
    range.addEventListener("input", touched);
    range.addEventListener("keydown", touched);
  }
}

