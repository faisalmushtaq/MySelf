/* ── Speaking instead of typing ──────────────────────────────────────────── */

/**
 * The recordings made in this run, as WhatsApp shows them.
 *
 * Kept in the page as well as in the bucket, because the bucket copy is
 * deliberately unreadable by any client — so the only way a participant can
 * hear back what they just said is the blob their own device still holds.
 * Cleared when the tab goes, which is the right lifetime for a playback aid.
 */
const voiceNotes: {
  url: string;
  seconds: number;
  kept: boolean;
  claimedBy: number | null;
  /** Bar heights, 0 to 1, taken from what the meter heard while recording. */
  shape: number[];
}[] = [];

/** How many bars a voice note is drawn with. WhatsApp's is about this many. */
const WAVE_BARS = 34;

/**
 * The recording's own shape, from the levels the meter collected.
 *
 * Downsampled by taking the PEAK of each bucket rather than the mean: a mean
 * flattens speech into a uniform sausage, because most of any sentence is
 * quieter than its loudest syllable. Peaks are what make a waveform look like
 * the thing that was said.
 *
 * Falls back to a flat-ish row when there were no levels — a browser with no
 * AudioContext still gets a voice note, it just gets a plain one.
 */
function shapeOf(levels: number[]): number[] {
  if (levels.length === 0) return Array.from({ length: WAVE_BARS }, (_, i) => 0.25 + ((i * 7) % 5) / 12);
  const size = levels.length / WAVE_BARS;
  const loudest = Math.max(...levels, 0.001);
  return Array.from({ length: WAVE_BARS }, (_, i) => {
    let peak = 0;
    for (let j = Math.floor(i * size); j < Math.max(Math.floor((i + 1) * size), Math.floor(i * size) + 1); j += 1) {
      peak = Math.max(peak, levels[j] ?? 0);
    }
    // Normalised against the loudest moment, so a quiet speaker still gets a
    // waveform with shape in it rather than a flat line.
    return Math.max(0.12, Math.min(1, peak / loudest));
  });
}
/**
 * Faults, kept so a re-render does not wipe the thing somebody is reading.
 *
 * Two layers on purpose. `text` is what a ten-year-old reads and can act on;
 * `detail` is the exception message, which is lab-only and never shown in the
 * participant view. Putting the raw error in front of a child is how "that is
 * not a recording this relay understands" ended up in somebody's chat.
 */
const troubles: { text: string; detail?: string }[] = [];

/**
 * Tie any loose recordings to the answer just sent.
 *
 * A clip is made before the message goes, so at the moment of sending, every
 * unclaimed note belongs to that message and should sit directly above it.
 */
function claimVoiceNotes(seq: number): void {
  for (const note of voiceNotes) if (note.claimedBy === null) note.claimedBy = seq;
}

/**
 * The sequence the answer about to be sent will be recorded under.
 *
 * The record does not exist yet — the runner appends it — so this is the next
 * one it will use. If it turns out to be wrong the note simply falls to the
 * bottom of the thread rather than sitting above its answer, which is a
 * cosmetic miss and not a lost recording.
 */
function nextRecordSeq(): number {
  const records = localRunner?.all ?? [];
  return (records[records.length - 1]?.seq ?? 0) + 1;
}

const mmss = (seconds: number) => `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, "0")}`;

/**
 * A voice note bubble, on the participant's side.
 *
 * Rendered outside the record-driven thread and re-appended after each render,
 * because the records hold the transcript — the words — and the audio is a
 * separate thing living only on this device. Trying to drive it from the
 * records would mean putting a blob URL in a research record, which is a URL
 * that means nothing five minutes later and nothing at all to an analyst.
 */
function renderVoiceNotes(): void {
  const thread = $("thread");
  for (const existing of thread.querySelectorAll(".voice-note")) existing.remove();
  for (const existing of thread.querySelectorAll(".trouble")) existing.remove();
  for (const note of voiceNotes) {
    const el = document.createElement("div");
    el.className = "msg from-me turn voice-note";
    el.innerHTML = `<div class="bubble">
        <audio src="${note.url}" preload="metadata"></audio>
        <button type="button" class="vn-play" aria-label="Play what you said">
          <svg class="vn-icon-play" viewBox="0 0 24 24" aria-hidden="true"><path fill="currentColor" d="M8 5.5v13l11-6.5z"/></svg>
          <svg class="vn-icon-pause" viewBox="0 0 24 24" aria-hidden="true"><path fill="currentColor" d="M8 5.5h3v13H8zm5 0h3v13h-3z"/></svg>
        </button>
        <span class="vn-wave" aria-hidden="true">${note.shape
          .map((h) => `<i style="height:${Math.round(h * 100)}%"></i>`)
          .join("")}</span>
        <span class="vn-time">${mmss(note.seconds)}</span>
        <span class="meta">${clock()}${TICKS}</span>
      </div>`;
    const audio = el.querySelector("audio")!;
    const play = el.querySelector<HTMLButtonElement>(".vn-play")!;
    const bars = [...el.querySelectorAll<HTMLElement>(".vn-wave i")];
    const time = el.querySelector<HTMLElement>(".vn-time")!;

    /**
     * The bars fill as it plays, and the counter counts up.
     *
     * WhatsApp fills the waveform behind a moving dot and shows elapsed rather
     * than total time while playing. Both are what tell you it is actually
     * playing when the phone is on silent — which, for a young person handed a
     * phone in a classroom, is most of the time.
     */
    const paint = () => {
      const length = audio.duration && Number.isFinite(audio.duration) ? audio.duration : note.seconds;
      const through = length > 0 ? audio.currentTime / length : 0;
      bars.forEach((b, i) => b.classList.toggle("played", i / bars.length < through));
      time.textContent = audio.paused && audio.currentTime === 0 ? mmss(note.seconds) : mmss(Math.floor(audio.currentTime));
    };
    const stop = () => {
      el.classList.remove("playing");
      paint();
    };

    play.addEventListener("click", () => {
      if (audio.paused) {
        // One at a time, as a chat does. Two voice notes over each other is
        // nobody's idea of playback.
        for (const other of document.querySelectorAll<HTMLAudioElement>(".voice-note audio")) {
          if (other !== audio) other.pause();
        }
        void audio.play();
        el.classList.add("playing");
      } else {
        audio.pause();
        el.classList.remove("playing");
      }
    });
    audio.addEventListener("timeupdate", paint);
    audio.addEventListener("pause", stop);
    audio.addEventListener("ended", () => {
      audio.currentTime = 0;
      stop();
    });
    const anchor = note.claimedBy === null ? null : thread.querySelector(`[data-seq="${note.claimedBy}"]`);
    if (anchor) anchor.before(el);
    else thread.append(el);
  }
  for (const trouble of troubles) {
    const el = document.createElement("div");
    el.className = "msg system-msg turn trouble";
    el.innerHTML = `<div class="bubble system">${escapeHtml(trouble.text)}${
      trouble.detail ? `<span class="lab-only trouble-detail">${escapeHtml(trouble.detail)}</span>` : ""
    }</div>`;
    thread.append(el);
  }
  if (voiceNotes.length > 0 || troubles.length > 0) scrollThread();
}

/**
 * Something that went wrong, said in the conversation and left there.
 *
 * The banner under the header clears itself after a few seconds, which is fine
 * for "Alex can't take calls" and useless for a fault somebody is trying to
 * report to me. This puts it in the thread, where it stays, scrolls with
 * everything else and survives being screenshotted.
 */
function troubleInThread(text: string, detail?: string): void {
  troubles.push(detail ? { text, detail } : { text });
  renderVoiceNotes();
}


/**
 * Talking to it, and getting back text you can edit.
 *
 * A young person who finds writing hard should not be shut out of a method
 * whose whole subject is what they have to say.
 *
 * NOT THE BROWSER'S RECOGNISER. Safari transcribes by sending audio to Apple
 * and Chrome by sending it to Google, so the easy route would hand children's
 * voices to a processor nobody named in the approval. The clip goes to the
 * study's own relay, which holds the study's own key and calls the study's own
 * provider — the one already named, already covered, already paying for every
 * other call this page makes.
 *
 * NOTHING IS KEPT BUT THE WORDS. The recording exists in this tab for as long
 * as it takes to upload, and in the function for as long as it takes to
 * transcribe. It is written to no database and no bucket at either end. What
 * lands is text, in the box, where it can be read and corrected before it is
 * sent — so the participant sees what the study will have, and can change it,
 * which is not true of a voice note.
 */

/**
 * Which container to record in — decided by TRYING, not by asking.
 *
 * `isTypeSupported` cannot be trusted here. Safari answers true for
 * "audio/webm" and then throws NotSupportedError when you actually construct
 * the recorder with it, which is precisely the shape of failure that leaves a
 * microphone button doing nothing at all: the throw happened inside an async
 * handler, so nothing turned red, nothing was said, and nothing recorded.
 *
 * So each candidate is constructed for real and the first one that survives is
 * used, ending with no options at all — letting the browser pick whatever it
 * records natively, which is the case that cannot fail.
 */
const CLIP_TYPES = ["audio/webm;codecs=opus", "audio/webm", "audio/mp4", "audio/aac", "audio/ogg;codecs=opus", ""];

function makeRecorder(stream: MediaStream): MediaRecorder | null {
  for (const type of CLIP_TYPES) {
    try {
      if (type && MediaRecorder.isTypeSupported && !MediaRecorder.isTypeSupported(type)) continue;
      return type ? new MediaRecorder(stream, { mimeType: type }) : new MediaRecorder(stream);
    } catch {
      // Claimed to support it and could not. Try the next.
    }
  }
  return null;
}

/** Base64 without loading a second copy of the clip into a string by hand. */
async function base64Of(blob: Blob): Promise<string> {
  const buffer = new Uint8Array(await blob.arrayBuffer());
  let binary = "";
  for (let i = 0; i < buffer.length; i += 0x8000) {
    binary += String.fromCharCode(...buffer.subarray(i, i + 0x8000));
  }
  return btoa(binary);
}

/**
 * A hard ceiling on one clip, matching the function's.
 *
 * Somebody who taps the microphone and puts the phone in their pocket should
 * cost one upload, not a stream.
 */
const MAX_CLIP_MS = 120_000;

function wireMic(): void {
  const button = document.getElementById("micBtn") as HTMLButtonElement | null;
  if (!button) return;
  // Whether recording is possible at all. Which container it will use is
  // decided when the recorder is built, not now — see `makeRecorder`.
  if (typeof MediaRecorder === "undefined" || !navigator.mediaDevices?.getUserMedia) return;
  micSupported = true;
  showRightButton();

  let recorder: MediaRecorder | null = null;
  let capping: ReturnType<typeof setTimeout> | null = null;
  /** Set when the clip is being thrown away rather than transcribed. */
  let discarding = false;
  /** What the recorder actually chose, which is not always what was asked. */
  let recordedAs = "";
  /** When this clip began, for the length shown on the voice note. */
  let startedAt = 0;
  /**
   * How loud it was, moment by moment.
   *
   * Sampled off the live stream rather than decoded from the finished clip.
   * Two reasons: it is the only way to draw the bars WHILE somebody is
   * talking, which is the whole point of a live waveform; and it means the
   * bubble's waveform is the same measurement, so what you watched arrive is
   * what you see afterwards. Decoding an mp4 on an old iPhone to draw a
   * decoration would be the expensive way to get a worse answer.
   */
  let levels: number[] = [];
  let listening: { context: AudioContext; stop: () => void } | null = null;
  /** The counter, ticking in real seconds. */
  let ticking: ReturnType<typeof setInterval> | null = null;

  const bar = () => composerBar();
  const strip = () => $("recordingStrip");
  const timeLabel = () => $("recTime");
  const liveWave = () => $("recWave");

  /**
   * The waveform, while it is happening.
   *
   * A counter says the phone is running; bars that move when you speak say the
   * phone is hearing YOU, which is a different and better assurance — and the
   * one thing that tells somebody their microphone is pointed the wrong way
   * before they have said their whole answer to nothing.
   *
   * The last fifty samples, oldest scrolling off the left, which is how every
   * recorder anybody has used behaves.
   */
  const LIVE_BARS = 50;
  const drawLive = () => {
    const wave = liveWave();
    if (wave.childElementCount !== LIVE_BARS) {
      wave.innerHTML = "<i></i>".repeat(LIVE_BARS);
    }
    const recent = levels.slice(-LIVE_BARS);
    const bars = wave.children;
    for (let i = 0; i < LIVE_BARS; i += 1) {
      // Right-aligned, so the newest sample is always at the same edge.
      const level = recent[i - (LIVE_BARS - recent.length)] ?? 0;
      (bars[i] as HTMLElement).style.height = `${Math.max(8, Math.round(level * 100))}%`;
    }
  };

  /**
   * Show the recording strip in place of the message box.
   *
   * WhatsApp removes the pill entirely while you talk, and that removal is
   * half of what makes the state legible: there is nothing to type into
   * because the phone is listening. The counter is the other half.
   */
  const showStrip = (on: boolean) => {
    strip().hidden = !on;
    for (const el of bar().querySelectorAll<HTMLElement>(".composer-pill, .composer-plus")) el.hidden = on;
    if (!on) {
      bar().classList.remove("writing");
      // Now that the box can be measured, give it the height its contents
      // need — which is where a multi-line transcript gets its room.
      sizeMessageBox();
    }
  };

  const tick = () => {
    const seconds = Math.floor((Date.now() - startedAt) / 1000);
    timeLabel().textContent = `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, "0")}`;
  };

  const release = () => {
    if (capping) clearTimeout(capping);
    capping = null;
    if (ticking) clearInterval(ticking);
    ticking = null;
    listening?.stop();
    listening = null;
    recorder?.stream.getTracks().forEach((t) => t.stop());
    recorder = null;
    button.classList.remove("listening");
    button.setAttribute("aria-label", "Speak your answer");
    showStrip(false);
    showRightButton();
  };
  /** Stop and write it down — the microphone button, and the length cap. */
  const finish = () => {
    discarding = false;
    if (recorder?.state === "recording") recorder.stop();
    else release();
  };
  /**
   * Stop and throw it away. This is what sending does: the message is already
   * on its way, so transcribing what was said over the top of it would drop a
   * stray sentence into the next answer.
   */
  stopListening = () => {
    discarding = true;
    if (recorder?.state === "recording") recorder.stop();
    else release();
  };

  const send = async (clip: Blob) => {
    const seconds = Math.max(1, Math.round((Date.now() - startedAt) / 1000));
    if (clip.size === 0) {
      release();
      micTrouble("I didn\u2019t catch any sound there. Have another go, or type your answer instead.");
      return;
    }
    if (!relay) {
      release();
      micTrouble("That recording could not be sent. You can type your answer instead.", "no relay configured in this build");
      return;
    }
    const credential = linkKey ? `Link ${linkKey}` : await session.token().then((t) => (t ? `Bearer ${t}` : null));
    if (!credential) {
      release();
      micTrouble(
        "Something is wrong with this link, so that could not be sent. Do let whoever sent it to you know.",
        "no credential: not signed in and no link key",
      );
      return;
    }
    // The bubble first, the words after. Their own recording is a thing that
    // exists the instant they stop talking, and showing it then is what makes
    // the transcription feel like it is happening TO something rather than
    // being a gap with nothing on screen.
    const note = { url: URL.createObjectURL(clip), seconds, kept: false, claimedBy: null, shape: shapeOf(levels) };
    voiceNotes.push(note);
    renderVoiceNotes();
    button.classList.add("writing");
    bar().classList.add("writing");
    // Only the control that is doing something. Send sitting beside a
    // greyed-out microphone invites a press that would do nothing.
    const sendButton = document.getElementById("sendMsg") as HTMLButtonElement | null;
    if (sendButton) sendButton.hidden = true;
    if (ticking) clearInterval(ticking);
    ticking = null;
    timeLabel().textContent = "Writing it down\u2026";
    try {
      const res = await fetch(`${relay.replace(/\/llmRelay$/, "")}/transcribe`, {
        method: "POST",
        headers: { "content-type": "application/json", authorization: credential },
        body: JSON.stringify({
          audio: await base64Of(clip),
          mimeType: clip.type || recordedAs,
          protocolKey: ($("protocol") as HTMLSelectElement | null)?.value ?? "unknown",
          sessionId: sessionId ?? "unknown",
          seconds: Math.round((Date.now() - startedAt) / 1000),
        }),
      });
      const body = (await res.json()) as {
        text?: string;
        kept?: boolean;
        error?: { message?: string };
      };
      if (!res.ok || typeof body.text !== "string") {
        // The recording may still have been saved even though the words were
        // not. Show it, so nobody is told to say it all again.
        note.kept = body.kept === true;
        micTrouble(body.error?.message ?? "That could not be written down. You can type your answer instead.");
        return;
      }
      if (!body.text) {
        micTrouble("Nothing came through on that one. Have another go, or type your answer.");
        return;
      }
      /**
       * The recording, in the conversation.
       *
       * Shown from the local blob rather than from the bucket: the bucket copy
       * is not readable by any page by design, and re-downloading a file the
       * device already has to play it back would be daft. It lives for as long
       * as the tab does, which is exactly as long as anybody would want to
       * replay it.
       */
      note.kept = body.kept === true;
      // Added to whatever was already typed rather than replacing it.
      const box = messageBox();
      const had = box.value.replace(/\s+$/, "");
      box.value = had ? `${had} ${body.text}` : body.text;
      sizeMessageBox();
      box.focus();
      // The words arriving in the box is the last beat, and it is easy to
      // miss on a phone. A brief highlight says where to look.
      box.classList.add("just-heard");
      setTimeout(() => box.classList.remove("just-heard"), 1400);
    } catch (error) {
      // The real reason, not a shrug. A microphone that fails silently is the
      // bug this whole path already had once.
      micTrouble(
        "That could not be sent just now. Have another go, or type your answer instead.",
        String((error as Error).message ?? error),
      );
    } finally {
      button.classList.remove("writing");
      release();
    }
  };

  document.getElementById("recCancel")?.addEventListener("click", () => {
    if (!recorder) return;
    // Thrown away without a word: cancelling is a decision, not a fault, and
    // does not deserve a message telling somebody what they already did.
    stopListening?.();
  });

  /**
   * Start listening. Shared by the hold gesture and the tap.
   */
  const begin = async (): Promise<boolean> => {
    let stream: MediaStream;
    try {
      stream = await navigator.mediaDevices.getUserMedia({ audio: true });
    } catch (error) {
      const denied = (error as { name?: string }).name === "NotAllowedError";
      micTrouble(
        denied
          ? "Your phone did not allow the microphone. You can turn it on in Settings, or type your answer instead."
          : "The microphone would not turn on. You can type your answer instead.",
        denied ? undefined : String((error as Error).message ?? error),
      );
      return false;
    }

    const rec = makeRecorder(stream);
    if (!rec) {
      stream.getTracks().forEach((t) => t.stop());
      micTrouble("This browser will not record audio. You can type your answer instead.");
      return false;
    }
    recordedAs = rec.mimeType || "";

    /**
     * The meter. Off the same stream the recorder is using, so it costs one
     * extra node and no extra permission.
     */
    try {
      const Context = window.AudioContext ?? (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
      const context = new Context();
      // Created inside an async continuation, so the gesture that opened the
      // microphone no longer counts and the context arrives suspended — an
      // analyser on a suspended context reads pure silence, which draws a
      // flat line and looks exactly like a microphone that is not working.
      void context.resume();
      const analyser = context.createAnalyser();
      analyser.fftSize = 1024;
      context.createMediaStreamSource(stream).connect(analyser);
      const buffer = new Uint8Array(analyser.fftSize);
      let raf = 0;
      const read = () => {
        analyser.getByteTimeDomainData(buffer);
        // Root mean square about the midpoint: loudness, not the waveform's
        // instantaneous sign, which is what a bar should be tall for.
        let sum = 0;
        for (const v of buffer) {
          const d = (v - 128) / 128;
          sum += d * d;
        }
        levels.push(Math.min(1, Math.sqrt(sum / buffer.length) * 3.2));
        drawLive();
        raf = requestAnimationFrame(read);
      };
      raf = requestAnimationFrame(read);
      listening = {
        context,
        stop: () => {
          cancelAnimationFrame(raf);
          void context.close();
        },
      };
    } catch {
      // No meter is survivable; no recording is not. The bars simply stay
      // flat and everything else behaves.
      listening = null;
    }

    const parts: Blob[] = [];
    rec.ondataavailable = (e) => {
      if (e.data.size > 0) parts.push(e.data);
    };
    rec.onerror = () => {
      micTrouble("The recording stopped unexpectedly. You can try again, or type your answer instead.");
      release();
    };
    rec.onstop = () => {
      // The tracks stop here rather than after the upload, as Bolo does it:
      // otherwise iOS keeps the orange recording dot lit for the seconds the
      // transcription takes, which looks like it is still listening.
      stream.getTracks().forEach((t) => t.stop());
      if (discarding) {
        release();
        return;
      }
      void send(recordedAs ? new Blob(parts, { type: recordedAs }) : new Blob(parts));
    };
    try {
      /**
       * No timeslice. This is the one line copied deliberately from Bolo,
       * which records on these same phones and works.
       *
       * `start(1000)` seemed the safer choice and is the opposite on iOS:
       * asking Safari for periodic chunks makes it emit FRAGMENTED MP4, and
       * the concatenation of those fragments is not a file a decoder will
       * open. One blob at the end is one valid file.
       */
      rec.start();
    } catch (error) {
      stream.getTracks().forEach((t) => t.stop());
      micTrouble(`The recording would not start (${String((error as Error).message ?? error)}).`);
      return false;
    }
    recorder = rec;
    startedAt = Date.now();
    capping = setTimeout(finish, MAX_CLIP_MS);
    button.classList.add("listening");
    button.setAttribute("aria-label", "Stop and write it down");
    // The counter starts at 0:00 immediately rather than a second later:
    // a beat of blank where the number should be reads as a stall.
    timeLabel().textContent = "0:00";
    showStrip(true);
    ticking = setInterval(tick, 200);
    showRightButton();
    return true;
  };

  /**
   * Hold to talk, slide to cancel, slide up to lock — and tap as the way in
   * for anybody the gesture does not suit.
   *
   * WhatsApp's gesture is the one a young person already has, and its two
   * escapes are the reason it works: you can back out of a recording without
   * sending it, and you can stop holding without losing it. Both are built
   * here. What is NOT copied is making the hold the only way: a child with a
   * tremor, somebody on a laptop, and anybody using a switch all need a press
   * that does not have to be maintained, so a quick tap starts a locked
   * recording and a second tap sends it.
   */
  const SLIDE_TO_CANCEL = 70;
  const SLIDE_TO_LOCK = 55;
  /** Under this, the press was a tap and the recording stays on by itself. */
  const TAP_MS = 350;

  let pressId: number | null = null;
  let pressAt = 0;
  let from = { x: 0, y: 0 };
  let locked = false;
  let cancelling = false;

  const setCancelling = (on: boolean) => {
    cancelling = on;
    strip().classList.toggle("cancelling", on);
  };

  const lock = () => {
    locked = true;
    pressId = null;
    strip().classList.remove("held");
    strip().classList.add("locked");
    setCancelling(false);
  };

  button.addEventListener("pointerdown", (event) => {
    // A press while locked is the stop button.
    if (recorder) {
      finish();
      return;
    }
    if (busy) return;
    pressId = event.pointerId;
    pressAt = Date.now();
    from = { x: event.clientX, y: event.clientY };
    locked = false;
    setCancelling(false);
    button.setPointerCapture?.(event.pointerId);
    void (async () => {
      const started = await begin();
      // Let go before the microphone opened: do not leave it running.
      if (!started) {
        pressId = null;
        return;
      }
      // The finger may already be gone: opening a microphone takes long enough
      // for a quick tap to have finished before this resolves. Let go with
      // nothing locked and there is nothing to keep; let go into a lock and the
      // strip is already in its locked state and must not be dressed as held.
      if (pressId === null) {
        if (!locked) stopListening?.();
        return;
      }
      strip().classList.add("held");
    })();
  });

  button.addEventListener("pointermove", (event) => {
    if (pressId !== event.pointerId || locked || !recorder) return;
    const left = from.x - event.clientX;
    const up = from.y - event.clientY;
    if (up > SLIDE_TO_LOCK && up > left) {
      lock();
      return;
    }
    setCancelling(left > SLIDE_TO_CANCEL);
    // The strip follows the finger, which is what tells you the slide is
    // doing something before you have gone far enough for it to.
    strip().style.setProperty("--slide", `${Math.min(left, 120)}px`);
  });

  const letGo = (event: PointerEvent) => {
    if (pressId !== event.pointerId) return;
    pressId = null;
    strip().classList.remove("held");
    strip().style.removeProperty("--slide");
    if (locked) return;

    // A tap, not a hold. The recording carries on by itself and the next tap
    // sends it — the forgiving path, and the only one a keyboard has.
    if (Date.now() - pressAt < TAP_MS && !cancelling) {
      lock();
      return;
    }
    if (cancelling) {
      setCancelling(false);
      stopListening?.();
      return;
    }
    finish();
  };
  button.addEventListener("pointerup", letGo);
  button.addEventListener("pointercancel", letGo);
  // Holding a button on iOS otherwise raises the selection callout.
  button.addEventListener("contextmenu", (event) => event.preventDefault());

  // The keyboard has no hold. Space and Enter start and stop.
  button.addEventListener("keydown", (event) => {
    if (event.key !== "Enter" && event.key !== " ") return;
    event.preventDefault();
    if (recorder) {
      finish();
      return;
    }
    void (async () => {
      if (await begin()) lock();
    })();
  });
}

/**
 * Show or hide the bar for this screen.
 *
 * Focus is taken only when the bar first appears in a run. After that the
 * element survives every turn, so focus survives with it and the keyboard
 * never closes — which is the whole point of not rebuilding it.
 */
function setComposer(placeholder: string | null): void {
  const bar = composerBar();
  if (placeholder === null) {
    bar.hidden = true;
    return;
  }
  const appearing = bar.hidden;
  bar.hidden = false;
  messageBox().placeholder = placeholder;
  if (appearing) {
    sizeMessageBox();
    if (document.body.classList.contains("participant-view")) messageBox().focus();
  }
}

/**
 * How many of the retellings have arrived.
 *
 * They used to land as one block: three paragraphs appearing in the same
 * frame, which shoves the conversation off the top of the screen and reads as
 * the page breaking rather than as somebody sending you something. Reset when
 * a new set is generated, and stepped up by `deliverChoices`.
 */
let choicesDelivered = 0;
let delivering = false;

/**
 * Send them one at a time, with the dots in between, as messages.
 *
 * Each one gets a pause the length of the message before it — the same rule as
 * every other bubble — but capped harder, because three of those in a row is a
 * different kind of wait from one. What matters is that they arrive as three
 * separate acts rather than one dump.
 */
async function deliverChoices(all: string[], hint: string): Promise<void> {
  if (delivering) return;
  delivering = true;
  try {
    while (choicesDelivered < all.length) {
      const html = all[choicesDelivered]!;
      // The instruction goes up once, before the first of them.
      if (choicesDelivered === 0) $("thread").insertAdjacentHTML("beforeend", hint);

      const dots = document.createElement("div");
      dots.className = "msg from-them turn";
      dots.innerHTML = `<div class="bubble"><span class="dots"><span></span><span></span><span></span></span></div>`;
      $("thread").append(dots);
      scrollThread();
      // Long enough to read as composing, short enough that three of them do
      // not become a minute of waiting.
      await wait(Math.min(1400, 400 + (all[choicesDelivered]!.length - 300) * 2));
      dots.remove();

      $("thread").insertAdjacentHTML("beforeend", html);
      choicesDelivered += 1;
      scrollThread();
      // Wired as each one lands, so the first can be held before the third
      // has arrived.
      wireStageControls();
      await wait(320);
    }
  } finally {
    delivering = false;
  }
}

function render(frame: Frame): void {
  const s = frame.screen;
  currentKind = s.kind;
  // A screen with no retellings on it resets the count, so the next set is
  // delivered rather than assumed to have already arrived.
  if ((s.choices ?? []).length === 0) choicesDelivered = 0;

  // How far along. Announced politely rather than assertively: a screen reader
  // being interrupted to say "step 4 of 6" in the middle of reading the
  // question is worse than not being told.
  $("progress").innerHTML = s.progress
    ? `<div class="progress">
         <div class="progress-track" role="progressbar" aria-valuenow="${s.progress.step}"
              aria-valuemin="1" aria-valuemax="${s.progress.of}"
              aria-label="How far through this part you are"
              aria-valuetext="${s.finished ? "finished" : `step ${s.progress.step} of ${s.progress.of}`}">
           <div class="progress-fill" style="width: ${Math.round((s.progress.step / s.progress.of) * 100)}%"></div>
         </div>
       </div>`
    : "";

  /* ── The stage area: what this screen asks the participant to DO ──────── */

  /**
   * The three retellings arrive as messages, and you react to one.
   *
   * They were radio cards, which is a form. In a chat you hold a message down
   * and put a thumb on it, so that is what this is: three bubbles from the
   * other side, press and hold to pick. The gesture is the one they already
   * use every day, and it is told to them in words above, because a gesture
   * nobody mentions is a gesture half of them will not find.
   *
   * A plain tap and the keyboard both work too. Long-press is the taught
   * gesture, not the only one — somebody on a laptop, or using a switch, must
   * not be stranded at the one screen the whole method turns on.
   *
   * The persona key is still lab-only: a card labelled "their words"
   * advertises itself as the honest one, and which they choose is the data.
   */
  const choiceHtml = (s.choices ?? []).map(
    // Three messages in one run, so the tail and the wider gap go on the
    // first only — the same rule the rest of the thread follows.
    (c, i) => `<div class="msg from-them ${i === 0 ? "turn " : ""}choice-msg">
          <div class="bubble choice-bubble" role="button" tabindex="0" data-choice="${c.index}"
               aria-label="Retelling. Press and hold to choose it, or press Enter to select it.">
            <span class="who lab-only">${escapeHtml(c.persona)}</span>
            ${escapeHtml(c.text)}
            <span class="reaction" aria-hidden="true">\u{1F44D}</span>
          </div>
        </div>`,
  );
  // Only the ones already delivered go into this pass; the rest arrive after
  // it, one at a time. See `deliverChoices`.
  const choices = choiceHtml.slice(0, choicesDelivered).join("");

  /**
   * The conversation, including the retellings.
   *
   * The three used to be rendered into the panel below the thread, which was a
   * second scrolling box stacked under the first. They scrolled independently,
   * so a retelling could sit half above a boundary with nothing to show it had
   * been cut — the "distorted" boxes. They are messages; they belong in the
   * thread, with the instruction as a centred system line above them, which is
   * where WhatsApp puts anything that is not a message.
   */
  const hint = choiceHtml.length > 0
    ? bubble("system", "Press and hold the one that fits best to give it a \u{1F44D} \u2014 or tap it, then press the button.")
    : "";
  $("thread").innerHTML =
    (threadFrom(frame.records) || `<p class="note">Start a run to see the conversation.</p>`) +
    (choicesDelivered > 0 ? hint : "") +
    choices;
  // The audio and any faults live outside the records, so they are put back
  // after every rebuild rather than being lost with the innerHTML.
  renderVoiceNotes();
  scrollThread();
  if (choiceHtml.length > choicesDelivered) void deliverChoices(choiceHtml, hint);

  // A slider with named ends, as the original has it: "needs a lot of work"
  // to "this looks good". Eleven radio buttons is a developer's idea of a
  // rating scale, and it reads as a form rather than an opinion.
  /**
   * The rating, which starts UNSET.
   *
   * It used to be born at the maximum, and Continue submitted whatever the
   * slider held. So a participant who never touched it — or, as happened, who
   * never even saw it because the panel had been squeezed off the screen —
   * had a perfect score recorded in their name. That is not a UI bug, it is a
   * measurement being invented, and it is the worst kind because the number
   * looks like data.
   *
   * The handle now sits in the middle as a starting point, the readout says
   * nothing until it is moved, and the button that submits it is disabled
   * until it has been. A rating has to be an act.
   */
  const rating = s.rating
    ? `<div class="slider-wrap">
         <p class="slider-ask">How well does it fit? Drag the slider to say.</p>
         <div class="slider-ends"><span class="low">needs a lot of work</span><span class="high">this looks good</span></div>
         <input type="range" id="ratingRange" min="0" max="${s.rating.max}" value="${Math.round(s.rating.max / 2)}"
                step="1" data-set="no" aria-label="How well it fits, from 0 to ${s.rating.max}" />
         <p class="slider-value"><span id="ratingValue">\u2014</span></p>
       </div>`
    : "";

  // The adapt stage, split the way the original splits it: rewrite it
  // yourself, or ask the model to. Two different acts producing two different
  // kinds of data, so two visibly different panels.
  const adapt = s.editable
    ? `<div class="adapt-block">
         <h3>Change it yourself</h3>
         <textarea id="scenarioEdit" class="scenario-edit" rows="7">${escapeHtml(s.scenario ?? "")}</textarea>
         <p class="hint-right">Press \u2318/Ctrl + Enter to keep it</p>
         <div class="row">
           <button class="secondary" id="revert">Reset to the last version</button>
           <button class="primary" id="keep">I&rsquo;m happy with this</button>
         </div>
       </div>
       <div class="adapt-ai">
         <h3>Or ask for a rewrite</h3>
         ${
           s.needsRequest
             ? `<p class="note warn-text">Tell me what to change and I will rewrite it \u2014 or edit it yourself above.</p>`
             : ""
         }
         ${
           s.unchanged
             ? `<p class="note warn-text">I could not make that change from your own words, so I left it as it was.</p>`
             : ""
         }
         <div class="composer">
           <textarea id="rewrite" rows="1" placeholder="Describe what you&rsquo;d like to change\u2026"></textarea>
           <button class="primary send-round" id="sendRewrite" title="Ask for a rewrite"><svg viewBox="0 0 24 24" aria-hidden="true"><path fill="currentColor" d="M3.4 20.4 21.8 12 3.4 3.6 3.4 10.1 16.5 12 3.4 13.9z"/></svg></button>
         </div>
       </div>`
    : "";

  // The retelling under discussion, quoted, at the stage where it is rated.
  const quoted = s.scenario && !s.editable ? `<blockquote class="scenario">${escapeHtml(s.scenario)}</blockquote>` : "";

  /**
   * Whether this screen is one somebody types a message on.
   *
   * The bar itself is permanent \u2014 see `setComposer`. This only decides whether
   * it is on screen, and it is off at the screens where the answer is a
   * gesture: choosing a retelling, dragging the rating, the closing screen.
   */
  const typing = s.expectsInput && choiceHtml.length === 0 && !rating && !s.editable && !s.finished;

  /**
   * The end, said properly.
   *
   * "Finished." in grey type is a status line, and it leaves somebody sitting
   * on a page wondering whether something else is coming. They have just spent
   * ten minutes telling us something; the least the last screen can do is
   * thank them, tell them they are done, and say what to do with the tab.
   *
   * The return button appears only when the link carried a `done` address, and
   * only for http(s) — an unchecked URL here would accept `javascript:` and
   * turn the last screen of a study into a script somebody else wrote.
   */
  const advance = s.finished
    ? `<div class="ending">
         <p class="ending-title">That is everything — thank you.</p>
         <p class="note">${
           s.stopped
             ? escapeHtml(`We stopped early: ${s.stopped.reason}. Nothing you wrote has been lost.`)
             : "Your answers have been saved. You can close this page now."
         }</p>
         ${returnLink ? `<div class="row"><a class="secondary button-link" href="${escapeHtml(returnLink)}">Back to the website</a></div>` : ""}
       </div>`
    : s.editable
      ? ""
      : (() => {
          // Nothing to press when the answer is typed or held: the bar and the
          // bubbles are the controls. A Continue button beside them is the one
          // that used to walk out of an unanswered interview.
          const button = typing || choices ? "" : `<button class="primary" id="${s.expectsInput ? "send" : "cont"}">Continue</button>`;
          const skip = s.optional ? '<button class="secondary" id="skip">Leave it as it is</button>' : "";
          return button || skip ? `<div class="row">${button}${skip}</div>` : "";
        })();

  const confirmRow = choiceHtml.length > 0
    ? `<div class="confirm-row">
         <button class="primary" id="confirmChoice" type="button" hidden>Choose this one \u{1F44D}</button>
       </div>`
    : "";

  $("stageArea").innerHTML = `${quoted}${confirmRow}${rating}${adapt}${advance}`;
  setComposer(typing ? "Message" : null);

  $("fallbackNote").innerHTML = s.fallback
    ? `<div class="alert"><strong>Fallback applied:</strong> ${escapeHtml(s.fallback.reason)} \u2192
       <code>${escapeHtml(s.fallback.applied)}</code>. Nothing the participant said was lost.</div>`
    : "";
  $("controls").innerHTML = "";

  wireStageControls();

  $("records").querySelector("tbody")!.innerHTML = frame.records
    .map(
      (r) => `<tr><td>${r.seq}</td><td class="src-${r.source}">${r.source}</td>
        <td><code>${r.kind}</code></td>
        <td class="wrapcell">${escapeHtml(r.text ?? (r.data ? JSON.stringify(r.data) : ""))}</td></tr>`,
    )
    .join("");

  if (frame.calls.length > 0) {
    $("calls").querySelector("tbody")!.innerHTML = frame.calls
      .map(
        (c) => `<tr><td>${c.stage}</td><td>${escapeHtml(c.modelServed ?? c.modelRequested)}</td>
          <td>${c.status}${c.errorKind ? ` <span class="badge warn">${c.errorKind}</span>` : ""}</td>
          <td>${c.latencyMs ?? "—"}</td>
          <td>${c.usage ? `${c.usage.inputTokens ?? "?"}/${c.usage.outputTokens ?? "?"}` : "—"}</td>
          <td>${c.containedIdentifiers ? '<span class="badge warn">yes</span>' : "no"}</td></tr>`,
      )
      .join("");
  }
}

// ── Driving a run ─────────────────────────────────────────────────────────

/**
 * What is happening while nothing is happening.
 *
 * A live model call is seconds, not milliseconds, and the stage after the
 * interview makes several: extract, then one retelling per persona. Without
 * this the page sits there after a click, which reads as broken — the first
 * live run of this looked "slow and glitchy" for exactly that reason, and the
 * retellings appeared to never arrive when in fact nobody had waited.
 *
 * The wording is per stage, because "working…" does not tell anyone whether to
 * keep waiting. A participant is told how many pieces of writing are coming.
 */
/**
 * The stages where somebody is composing a reply, and dots belong.
 *
 * Choosing, rating and the closing screen call nothing, so dots there would be
 * a bot pretending to think.
 */
const THINKS = new Set(["introduction", "collect", "extract", "generate", "adapt", "follow_up", "interpret"]);

/**
 * How long the dots stay up, and why it depends on what is coming.
 *
 * A reply that lands in 200ms flashes the dots for a frame, which reads as a
 * glitch. But a FIXED floor has the opposite problem at the other end: the
 * introduction is a ninety-word paragraph, and ninety words arriving whole
 * two-thirds of a second after a tap is the clearest possible tell that
 * nothing typed them. The illusion breaks before the conversation starts.
 *
 * So the wait is proportional to the message: roughly nine milliseconds a
 * character over a half-second floor, ceilinged just under four seconds so the
 * longest thing in the protocol does not become a wait. Nobody types 450
 * characters instantly, and nobody takes a real minute either — this is
 * imitating somebody composing on a phone, not a transcriptionist.
 *
 * Short replies barely change: a twelve-word question still lands in about a
 * second. It is the paragraph that now takes its time.
 */
const DOTS_FLOOR_MS = 500;
const DOTS_CEILING_MS = 3800;
const MS_PER_CHARACTER = 9;

export function typingPause(text: string | null | undefined): number {
  const characters = (text ?? "").trim().length;
  return Math.min(DOTS_CEILING_MS, DOTS_FLOOR_MS + characters * MS_PER_CHARACTER);
}

/**
 * What the pause is measured against — and the one screen it is not.
 *
 * Everywhere else the rule is "as long as it would take to type this". The
 * retellings are the deliberate exception: three paragraphs landing together
 * are not somebody typing, they are a set of options being put in front of
 * you, and pausing for the length of all three would be ten seconds of wait
 * dressed as courtesy. That stage has also just made several real model calls,
 * so the participant has already done the waiting that counts.
 *
 * The retellings live in `choices` rather than `text`, so they were never
 * measured — but this says so, rather than leaving it true by accident until
 * somebody moves a field.
 */
function pauseFor(screen: Screen): string | null {
  if ((screen.choices ?? []).length > 0) return null;
  return screen.text ?? null;
}

let dotsShownAt = 0;

const wait = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

/**
 * Hold until the dots have been up long enough, then let the reply land.
 *
 * Before the render, not after: rendering rebuilds the thread from the records
 * and takes the dots with it, so a delay on the other side would keep the page
 * busy after the answer was already on screen — which is a pause with nothing
 * to look at, the opposite of the intent.
 */
async function settle(coming?: string | null): Promise<void> {
  if (dotsShownAt === 0) return;
  const shown = Date.now() - dotsShownAt;
  // The model's own latency counts towards it. A call that took two seconds
  // has already spent two seconds of somebody's patience, and adding a full
  // typing pause on top would be theatre charged for twice.
  const wanted = typingPause(coming);
  if (shown < wanted) await wait(wanted - shown);
  dotsShownAt = 0;
}

let busy = false;
/** The kind of stage on screen, so the waiting note can say what is coming. */
let currentKind = "introduction";

function setBusy(stageKind: string | null): void {
  busy = stageKind !== null;
  /**
   * A button held shut on purpose stays shut.
   *
   * This runs at the end of every turn and used to set `disabled = busy` on
   * everything in the stage area — which re-enabled the submit button that the
   * rating had just locked, because the render happens before this does. The
   * gate was defeated by the housekeeping that came after it.
   */
  document
    .querySelectorAll<HTMLButtonElement>("#stageArea button")
    .forEach((b) => (b.disabled = busy || b.dataset["gate"] === "shut"));
  document.querySelectorAll<HTMLTextAreaElement>("#stageArea textarea").forEach((t) => (t.disabled = busy));
  /**
   * The send button goes grey; the message box does not.
   *
   * Disabling a focused textarea blurs it, and on iOS a blur closes the
   * keyboard and resizes the viewport — the exact churn the permanent composer
   * exists to avoid. Typing ahead while a reply is coming is what a chat does
   * anyway, and a second send is refused at the top of `turn` regardless.
   */
  const send = document.getElementById("sendMsg") as HTMLButtonElement | null;
  if (send) send.disabled = busy;

  const existing = document.getElementById("thinking");
  // Choosing, rating and the closing screen call nothing, so a bot pretending
  // to think there would be theatre.
  if (stageKind === null || !THINKS.has(stageKind)) {
    existing?.remove();
    setStatus(false);
    return;
  }
  setStatus(true);
  if (existing) return;

  // The dots go in the thread, on the bot's side, where its reply will
  // appear — not on a spinner elsewhere on the page. That is what makes a
  // wait read as someone composing an answer rather than as a stall.
  const node = document.createElement("div");
  node.id = "thinking";
  node.className = "msg from-them turn";
  node.innerHTML = `<div class="bubble"><span class="dots"><span></span><span></span><span></span></span></div>`;
  $("thread").append(node);
  dotsShownAt = Date.now();
  scrollThread();
}

/** When this run began, for the elapsed time the original also recorded. */
let runStartedAt = 0;

/**
 * Keep the run, as it happens.
 *
 * Sent after every turn rather than at the end, because most of what is worth
 * reading from a test is in the runs that did not finish — somebody who gave
 * up at the rating screen has told you something, and an end-of-run save loses
 * exactly those.
 *
 * It never blocks the conversation and never surfaces an error to the person
 * talking. A participant cannot do anything about a failed write, and stopping
 * them mid-sentence to say so would cost the answer as well as the record. The
 * whole log is re-sent each time, so the next successful write repairs any
 * that were missed.
 */
async function store(runner: NarrativeRunner, finished: boolean): Promise<void> {
  if (!relay) return;
  const credential = linkKey ? `Link ${linkKey}` : await session.token().then((t) => (t ? `Bearer ${t}` : null));
  if (!credential) return;

  const records = runner.all;
  if (records.length === 0) return;

  try {
    const res = await fetch(`${relay.replace(/\/llmRelay$/, "")}/saveNarrative`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: credential },
      body: JSON.stringify({
        sessionId: records[0]!.sessionId,
        protocolKey: records[0]!.protocolKey,
        protocolVersion: records[0]!.protocolVersion,
        records,
        finished,
        elapsedSeconds: runStartedAt ? Math.round((Date.now() - runStartedAt) / 1000) : 0,
      }),
    });
    /**
     * Blue ticks mean it is stored, and only that.
     *
     * WhatsApp's blue ticks mean read, and borrowing them for decoration would
     * be a small lie in the one part of the screen that is about whether their
     * words survived. Here they say the run reached the study — which is the
     * honest equivalent, and the thing a participant would actually want to
     * know.
     */
    document.body.classList.toggle("saved", res.ok);
  } catch {
    // Deliberately silent — see above.
  }
}

async function turn(payload: { action: string; input?: string; echo?: boolean }): Promise<void> {
  // Ignore a second click while a call is in flight: double-submitting a turn
  // is how a participant ends up paying for two interviews of themselves.
  if (busy) return;

  /**
   * Their message, on screen the instant they send it.
   *
   * The thread is rebuilt from the records, and the records only come back
   * when the model does — so until now, sending an answer made it disappear
   * for the several seconds the call takes, and the dots appeared where the
   * reply would go. You could watch your own sentence vanish.
   *
   * No messaging app has ever worked that way. The bubble goes up
   * immediately and is replaced by the recorded one when the turn returns,
   * which is the same text: this is the appearance arriving early, not a
   * second copy or an optimistic guess about what will be stored.
   */
  const said = payload.echo === true ? payload.input?.trim() : undefined;
  if (said) {
    // Whatever was recorded for this answer belongs above it.
    claimVoiceNotes(nextRecordSeq());
    $("thread").insertAdjacentHTML("beforeend", bubble("me", escapeHtml(said)));
    scrollThread();
  }

  setBusy(currentKind);
  try {
    if (localRunner) {
      const screen =
        payload.action === "next"
          ? await localRunner.next()
          : payload.action === "skip"
            ? await localRunner.skip()
            : payload.action === "keep"
              ? await localRunner.keepScenario(payload.input ?? "")
              : payload.action === "revert"
                ? localRunner.revertScenario()
                : await localRunner.submit(payload.input ?? "");
      await settle(pauseFor(screen));
      render({ screen, records: localRunner.all, calls: localCalls });
      void store(localRunner, screen.finished);
      return;
    }
    const frame = await api<Frame>("/api/turn", { sessionId, ...payload });
    await settle(pauseFor(frame.screen));
    render(frame);
  } catch (error) {
    // A failed turn must not leave the page disabled and silent.
    $("stageArea").innerHTML =
      `<div class="alert"><strong>Something went wrong:</strong>
       ${escapeHtml(String((error as Error).message ?? error))}.
       Nothing that was written has been lost — it is in the records below.</div>`;
  } finally {
    setBusy(null);
  }
}

