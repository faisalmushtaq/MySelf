/** Wire whatever controls this stage put on screen. */
function wireStageControls(): void {
  /**
   * Press and hold a retelling to choose it.
   *
   * The gesture a young person already has for "this one" is holding a message
   * down and putting a thumb on it, so that is the gesture — and the thumb
   * lands on the bubble before the page moves on, because a choice that
   * vanishes the instant you make it does not feel like a choice.
   *
   * Tap and Enter do the same thing. Long-press is what the hint teaches, not
   * the only way in: nobody on a laptop, a keyboard or a switch should be
   * stranded at the one screen the whole method turns on.
   */
  for (const el of document.querySelectorAll<HTMLElement>(".choice-bubble")) {
    let held: ReturnType<typeof setTimeout> | null = null;
    let fired = false;

    const choose = () => {
      if (busy) return;
      fired = true;
      el.classList.add("chosen");
      el.classList.remove("holding");
      // Long enough to see the thumb land, short enough not to feel stuck.
      setTimeout(() => void turn({ action: "submit", input: el.dataset["choice"] ?? "" }), 320);
    };
    const cancel = () => {
      if (held) clearTimeout(held);
      held = null;
      el.classList.remove("holding");
    };

    el.addEventListener("pointerdown", () => {
      if (fired) return;
      el.classList.add("holding");
      held = setTimeout(choose, 420);
    });
    el.addEventListener("pointerup", () => {
      const wasHolding = held !== null;
      cancel();
      // A tap counts as well, so the hint is guidance rather than a gate.
      if (wasHolding && !fired) choose();
    });
    el.addEventListener("pointerleave", cancel);
    el.addEventListener("pointercancel", cancel);
    // Holding a bubble on iOS otherwise raises the text-selection callout.
    el.addEventListener("contextmenu", (event) => event.preventDefault());
    el.addEventListener("keydown", (event) => {
      if (fired) return;
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        choose();
      }
    });
  }

  const submit = () => {
    const picked = document.querySelector<HTMLInputElement>('input[name="choice"]:checked');
    const range = document.getElementById("ratingRange") as HTMLInputElement | null;
    // `echo` only when the value is something they wrote. A choice sends an
    // index and a rating sends a number, and neither is a sentence anybody
    // said — the thread renders those as "I'll take the plain one" and
    // "7 out of 10" once recorded, which is what should appear.
    void turn({ action: "submit", input: picked?.value ?? range?.value ?? "", echo: false });
  };

  document.getElementById("send")?.addEventListener("click", submit);
  document.getElementById("cont")?.addEventListener("click", () => void turn({ action: "next" }));
  document.getElementById("skip")?.addEventListener("click", () => void turn({ action: "skip" }));
  document.getElementById("revert")?.addEventListener("click", () => void turn({ action: "revert" }));
  document.getElementById("keep")?.addEventListener("click", () => {
    const edited = (document.getElementById("scenarioEdit") as HTMLTextAreaElement | null)?.value ?? "";
    void turn({ action: "keep", input: edited });
  });

  // The rewrite request at the adapt stage. Its own box rather than the message
  // bar: "describe what to change" is an instruction about a text, not a reply
  // in the conversation, and it sits beside the text it is about.
  const rewrite = document.getElementById("rewrite") as HTMLTextAreaElement | null;
  const askRewrite = () => {
    const said = rewrite?.value ?? "";
    if (!said.trim()) return;
    if (rewrite) rewrite.value = "";
    void turn({ action: "submit", input: said, echo: true });
  };
  document.getElementById("sendRewrite")?.addEventListener("click", askRewrite);
  rewrite?.addEventListener("keydown", (e) => {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      askRewrite();
    }
  });

  // Cmd/Ctrl+Enter keeps an edited write-up, as the original does.
  /**
   * Grow the retelling box to whatever came out of the model.
   *
   * They are being asked to read it closely enough to say what is wrong with
   * it and then to edit it, and a fixed seven-row box showed a nine-line
   * paragraph through a letterbox. Sized to content on render and again on
   * every keystroke, so it never scrolls internally while there is room on the
   * page.
   */
  const grow = (el: HTMLTextAreaElement) => {
    el.style.height = "auto";
    el.style.height = `${el.scrollHeight}px`;
  };
  const edit = document.getElementById("scenarioEdit") as HTMLTextAreaElement | null;
  if (edit) {
    grow(edit);
    edit.addEventListener("input", () => grow(edit));
  }
  edit?.addEventListener("keydown", (e) => {
    if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      void turn({ action: "keep", input: edit.value });
    }
  });

  document.querySelectorAll<HTMLInputElement>('input[name="choice"]').forEach((radio) => {
    radio.addEventListener("change", () => {
      document.querySelectorAll(".card-choice").forEach((c) => c.classList.remove("picked"));
      radio.closest(".card-choice")?.classList.add("picked");
    });
  });

  const range = document.getElementById("ratingRange") as HTMLInputElement | null;
  range?.addEventListener("input", () => {
    const out = document.getElementById("ratingValue");
    if (out) out.textContent = range.value;
  });
}

