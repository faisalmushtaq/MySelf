/* ── Speaking instead of typing ──────────────────────────────────────────── */

/**
 * Dictation, where the browser has it.
 *
 * The recogniser is the browser's own — Safari's and Chrome's both send audio
 * to their vendor to transcribe it, which is the same path as the dictation key
 * on the keyboard a participant already has. THIS PAGE RECORDS NOTHING: no
 * audio is captured by us, uploaded by us or stored anywhere, and what reaches
 * the study is the text, sitting in the box where it can be read and corrected
 * before it is sent. That distinction is the whole reason it is built this way
 * rather than as a voice note.
 *
 * It is offered only where a recogniser exists, because a microphone button
 * that cannot work is worse than no microphone button.
 */
interface SpeechLike {
  lang: string;
  continuous: boolean;
  interimResults: boolean;
  start(): void;
  stop(): void;
  onresult: ((event: { results: ArrayLike<ArrayLike<{ transcript: string }>> }) => void) | null;
  onerror: ((event: { error?: string }) => void) | null;
  onend: (() => void) | null;
}

function wireMic(): void {
  const button = document.getElementById("micBtn") as HTMLButtonElement | null;
  if (!button) return;
  const w = window as unknown as { SpeechRecognition?: new () => SpeechLike; webkitSpeechRecognition?: new () => SpeechLike };
  const Recogniser = w.SpeechRecognition ?? w.webkitSpeechRecognition;
  if (!Recogniser) return;
  micAvailable = true;
  showRightButton();

  let listening: SpeechLike | null = null;
  // What was in the box when they started talking, so speech is added to it
  // rather than replacing something they had already typed.
  let before = "";

  const stop = () => {
    listening?.stop();
    listening = null;
    button.classList.remove("listening");
    button.setAttribute("aria-label", "Speak your answer");
    showRightButton();
  };
  stopListening = stop;

  button.addEventListener("click", () => {
    if (listening) {
      stop();
      return;
    }
    const speech = new Recogniser();
    speech.lang = navigator.language || "en-GB";
    speech.continuous = true;
    speech.interimResults = true;

    speech.onresult = (event) => {
      let heard = "";
      for (let i = 0; i < event.results.length; i += 1) heard += event.results[i]?.[0]?.transcript ?? "";
      const box = messageBox();
      box.value = (before ? `${before.replace(/\s+$/, "")} ` : "") + heard.trim();
      sizeMessageBox();
    };
    speech.onerror = (event) => {
      stop();
      headerNote(
        event.error === "not-allowed"
          ? "Your browser did not allow the microphone. You can type your answer instead."
          : "That did not come through. You can try again, or type your answer instead.",
      );
    };
    speech.onend = () => stop();

    before = messageBox().value;
    try {
      speech.start();
    } catch {
      headerNote("The microphone could not be started. You can type your answer instead.");
      return;
    }
    listening = speech;
    button.classList.add("listening");
    button.setAttribute("aria-label", "Stop listening");
    showRightButton();
    messageBox().focus();
  });
}

/**
 * Show or hide the bar for this screen.
 *
 * Focus is taken only when the bar first appears in a run. After that the
 * element survives every turn, so focus survives with it and the keyboard
 * never closes — which is the whole point of not rebuilding it.
 */
function setComposer(placeholder: string | null): void {
  const bar = composerBar();
  if (placeholder === null) {
    bar.hidden = true;
    return;
  }
  const appearing = bar.hidden;
  bar.hidden = false;
  messageBox().placeholder = placeholder;
  if (appearing) {
    sizeMessageBox();
    if (document.body.classList.contains("participant-view")) messageBox().focus();
  }
}

function render(frame: Frame): void {
  const s = frame.screen;
  currentKind = s.kind;

  // How far along. Announced politely rather than assertively: a screen reader
  // being interrupted to say "step 4 of 6" in the middle of reading the
  // question is worse than not being told.
  $("progress").innerHTML = s.progress
    ? `<div class="progress">
         <div class="progress-track" role="progressbar" aria-valuenow="${s.progress.step}"
              aria-valuemin="1" aria-valuemax="${s.progress.of}"
              aria-label="How far through this part you are"
              aria-valuetext="${s.finished ? "finished" : `step ${s.progress.step} of ${s.progress.of}`}">
           <div class="progress-fill" style="width: ${Math.round((s.progress.step / s.progress.of) * 100)}%"></div>
         </div>
       </div>`
    : "";

  /* ── The stage area: what this screen asks the participant to DO ──────── */

  /**
   * The three retellings arrive as messages, and you react to one.
   *
   * They were radio cards, which is a form. In a chat you hold a message down
   * and put a thumb on it, so that is what this is: three bubbles from the
   * other side, press and hold to pick. The gesture is the one they already
   * use every day, and it is told to them in words above, because a gesture
   * nobody mentions is a gesture half of them will not find.
   *
   * A plain tap and the keyboard both work too. Long-press is the taught
   * gesture, not the only one — somebody on a laptop, or using a switch, must
   * not be stranded at the one screen the whole method turns on.
   *
   * The persona key is still lab-only: a card labelled "their words"
   * advertises itself as the honest one, and which they choose is the data.
   */
  const choices = (s.choices ?? [])
    .map(
      // Three messages in one run, so the tail and the wider gap go on the
      // first only — the same rule the rest of the thread follows.
      (c, i) => `<div class="msg from-them ${i === 0 ? "turn " : ""}choice-msg" style="animation-delay: ${i * 140}ms">
          <div class="bubble choice-bubble" role="button" tabindex="0" data-choice="${c.index}"
               aria-label="Retelling. Press and hold, or press Enter, to choose this one.">
            <span class="who lab-only">${escapeHtml(c.persona)}</span>
            ${escapeHtml(c.text)}
            <span class="reaction" aria-hidden="true">\u{1F44D}</span>
          </div>
        </div>`,
    )
    .join("");

  /**
   * The conversation, including the retellings.
   *
   * The three used to be rendered into the panel below the thread, which was a
   * second scrolling box stacked under the first. They scrolled independently,
   * so a retelling could sit half above a boundary with nothing to show it had
   * been cut — the "distorted" boxes. They are messages; they belong in the
   * thread, with the instruction as a centred system line above them, which is
   * where WhatsApp puts anything that is not a message.
   */
  const hint = choices
    ? bubble("system", "Press and hold the one that fits best, and give it a \u{1F44D}")
    : "";
  $("thread").innerHTML =
    (threadFrom(frame.records) || `<p class="note">Start a run to see the conversation.</p>`) + hint + choices;
  scrollThread();

  // A slider with named ends, as the original has it: "needs a lot of work"
  // to "this looks good". Eleven radio buttons is a developer's idea of a
  // rating scale, and it reads as a form rather than an opinion.
  const rating = s.rating
    ? `<div class="slider-wrap">
         <div class="slider-ends"><span class="low">needs a lot of work</span><span class="high">this looks good</span></div>
         <input type="range" id="ratingRange" min="0" max="${s.rating.max}" value="${s.rating.max}" step="1" />
         <p class="slider-value"><span id="ratingValue">${s.rating.max}</span> out of ${s.rating.max}</p>
       </div>`
    : "";

  // The adapt stage, split the way the original splits it: rewrite it
  // yourself, or ask the model to. Two different acts producing two different
  // kinds of data, so two visibly different panels.
  const adapt = s.editable
    ? `<div class="adapt-block">
         <h3>Change it yourself</h3>
         <textarea id="scenarioEdit" class="scenario-edit" rows="7">${escapeHtml(s.scenario ?? "")}</textarea>
         <p class="hint-right">Press \u2318/Ctrl + Enter to keep it</p>
         <div class="row">
           <button class="secondary" id="revert">Reset to the last version</button>
           <button class="primary" id="keep">I&rsquo;m happy with this</button>
         </div>
       </div>
       <div class="adapt-ai">
         <h3>Or ask for a rewrite</h3>
         ${
           s.needsRequest
             ? `<p class="note warn-text">Tell me what to change and I will rewrite it \u2014 or edit it yourself above.</p>`
             : ""
         }
         ${
           s.unchanged
             ? `<p class="note warn-text">I could not make that change from your own words, so I left it as it was.</p>`
             : ""
         }
         <div class="composer">
           <textarea id="rewrite" rows="1" placeholder="Describe what you&rsquo;d like to change\u2026"></textarea>
           <button class="primary send-round" id="sendRewrite" title="Ask for a rewrite"><svg viewBox="0 0 24 24" aria-hidden="true"><path fill="currentColor" d="M3.4 20.4 21.8 12 3.4 3.6 3.4 10.1 16.5 12 3.4 13.9z"/></svg></button>
         </div>
       </div>`
    : "";

  // The retelling under discussion, quoted, at the stage where it is rated.
  const quoted = s.scenario && !s.editable ? `<blockquote class="scenario">${escapeHtml(s.scenario)}</blockquote>` : "";

  /**
   * Whether this screen is one somebody types a message on.
   *
   * The bar itself is permanent \u2014 see `setComposer`. This only decides whether
   * it is on screen, and it is off at the screens where the answer is a
   * gesture: choosing a retelling, dragging the rating, the closing screen.
   */
  const typing = s.expectsInput && !choices && !rating && !s.editable && !s.finished;

  /**
   * The end, said properly.
   *
   * "Finished." in grey type is a status line, and it leaves somebody sitting
   * on a page wondering whether something else is coming. They have just spent
   * ten minutes telling us something; the least the last screen can do is
   * thank them, tell them they are done, and say what to do with the tab.
   *
   * The return button appears only when the link carried a `done` address, and
   * only for http(s) — an unchecked URL here would accept `javascript:` and
   * turn the last screen of a study into a script somebody else wrote.
   */
  const advance = s.finished
    ? `<div class="ending">
         <p class="ending-title">That is everything — thank you.</p>
         <p class="note">${
           s.stopped
             ? escapeHtml(`We stopped early: ${s.stopped.reason}. Nothing you wrote has been lost.`)
             : "Your answers have been saved. You can close this page now."
         }</p>
         ${returnLink ? `<div class="row"><a class="secondary button-link" href="${escapeHtml(returnLink)}">Back to the website</a></div>` : ""}
       </div>`
    : s.editable
      ? ""
      : (() => {
          // Nothing to press when the answer is typed or held: the bar and the
          // bubbles are the controls. A Continue button beside them is the one
          // that used to walk out of an unanswered interview.
          const button = typing || choices ? "" : `<button class="primary" id="${s.expectsInput ? "send" : "cont"}">Continue</button>`;
          const skip = s.optional ? '<button class="secondary" id="skip">Leave it as it is</button>' : "";
          return button || skip ? `<div class="row">${button}${skip}</div>` : "";
        })();

  $("stageArea").innerHTML = `${quoted}${rating}${adapt}${advance}`;
  setComposer(typing ? "Message" : null);

  $("fallbackNote").innerHTML = s.fallback
    ? `<div class="alert"><strong>Fallback applied:</strong> ${escapeHtml(s.fallback.reason)} \u2192
       <code>${escapeHtml(s.fallback.applied)}</code>. Nothing the participant said was lost.</div>`
    : "";
  $("controls").innerHTML = "";

  wireStageControls();

  $("records").querySelector("tbody")!.innerHTML = frame.records
    .map(
      (r) => `<tr><td>${r.seq}</td><td class="src-${r.source}">${r.source}</td>
        <td><code>${r.kind}</code></td>
        <td class="wrapcell">${escapeHtml(r.text ?? (r.data ? JSON.stringify(r.data) : ""))}</td></tr>`,
    )
    .join("");

  if (frame.calls.length > 0) {
    $("calls").querySelector("tbody")!.innerHTML = frame.calls
      .map(
        (c) => `<tr><td>${c.stage}</td><td>${escapeHtml(c.modelServed ?? c.modelRequested)}</td>
          <td>${c.status}${c.errorKind ? ` <span class="badge warn">${c.errorKind}</span>` : ""}</td>
          <td>${c.latencyMs ?? "—"}</td>
          <td>${c.usage ? `${c.usage.inputTokens ?? "?"}/${c.usage.outputTokens ?? "?"}` : "—"}</td>
          <td>${c.containedIdentifiers ? '<span class="badge warn">yes</span>' : "no"}</td></tr>`,
      )
      .join("");
  }
}

// ── Driving a run ─────────────────────────────────────────────────────────

/**
 * What is happening while nothing is happening.
 *
 * A live model call is seconds, not milliseconds, and the stage after the
 * interview makes several: extract, then one retelling per persona. Without
 * this the page sits there after a click, which reads as broken — the first
 * live run of this looked "slow and glitchy" for exactly that reason, and the
 * retellings appeared to never arrive when in fact nobody had waited.
 *
 * The wording is per stage, because "working…" does not tell anyone whether to
 * keep waiting. A participant is told how many pieces of writing are coming.
 */
/**
 * The stages where somebody is composing a reply, and dots belong.
 *
 * Choosing, rating and the closing screen call nothing, so dots there would be
 * a bot pretending to think.
 */
const THINKS = new Set(["introduction", "collect", "extract", "generate", "adapt", "follow_up", "interpret"]);

/**
 * How long the dots stay up at the least.
 *
 * A reply that lands in 200ms flashes the dots for a frame, which reads as a
 * glitch rather than as an answer. Messages has the same beat because a person
 * is typing on the other end; keeping it makes a fast reply feel composed
 * rather than canned, and costs a fifth of a second nobody is waiting on.
 */
const DOTS_AT_LEAST_MS = 650;
let dotsShownAt = 0;

const wait = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

/**
 * Hold until the dots have been up long enough, then let the reply land.
 *
 * Before the render, not after: rendering rebuilds the thread from the records
 * and takes the dots with it, so a delay on the other side would keep the page
 * busy after the answer was already on screen — which is a pause with nothing
 * to look at, the opposite of the intent.
 */
async function settle(): Promise<void> {
  if (dotsShownAt === 0) return;
  const shown = Date.now() - dotsShownAt;
  if (shown < DOTS_AT_LEAST_MS) await wait(DOTS_AT_LEAST_MS - shown);
  dotsShownAt = 0;
}

let busy = false;
/** The kind of stage on screen, so the waiting note can say what is coming. */
let currentKind = "introduction";

function setBusy(stageKind: string | null): void {
  busy = stageKind !== null;
  document.querySelectorAll<HTMLButtonElement>("#stageArea button").forEach((b) => (b.disabled = busy));
  document.querySelectorAll<HTMLTextAreaElement>("#stageArea textarea").forEach((t) => (t.disabled = busy));
  /**
   * The send button goes grey; the message box does not.
   *
   * Disabling a focused textarea blurs it, and on iOS a blur closes the
   * keyboard and resizes the viewport — the exact churn the permanent composer
   * exists to avoid. Typing ahead while a reply is coming is what a chat does
   * anyway, and a second send is refused at the top of `turn` regardless.
   */
  const send = document.getElementById("sendMsg") as HTMLButtonElement | null;
  if (send) send.disabled = busy;

  const existing = document.getElementById("thinking");
  // Choosing, rating and the closing screen call nothing, so a bot pretending
  // to think there would be theatre.
  if (stageKind === null || !THINKS.has(stageKind)) {
    existing?.remove();
    setStatus(false);
    return;
  }
  setStatus(true);
  if (existing) return;

  // The dots go in the thread, on the bot's side, where its reply will
  // appear — not on a spinner elsewhere on the page. That is what makes a
  // wait read as someone composing an answer rather than as a stall.
  const node = document.createElement("div");
  node.id = "thinking";
  node.className = "msg from-them turn";
  node.innerHTML = `<div class="bubble"><span class="dots"><span></span><span></span><span></span></span></div>`;
  $("thread").append(node);
  dotsShownAt = Date.now();
  scrollThread();
}

/** When this run began, for the elapsed time the original also recorded. */
let runStartedAt = 0;

/**
 * Keep the run, as it happens.
 *
 * Sent after every turn rather than at the end, because most of what is worth
 * reading from a test is in the runs that did not finish — somebody who gave
 * up at the rating screen has told you something, and an end-of-run save loses
 * exactly those.
 *
 * It never blocks the conversation and never surfaces an error to the person
 * talking. A participant cannot do anything about a failed write, and stopping
 * them mid-sentence to say so would cost the answer as well as the record. The
 * whole log is re-sent each time, so the next successful write repairs any
 * that were missed.
 */
async function store(runner: NarrativeRunner, finished: boolean): Promise<void> {
  if (!relay) return;
  const credential = linkKey ? `Link ${linkKey}` : await session.token().then((t) => (t ? `Bearer ${t}` : null));
  if (!credential) return;

  const records = runner.all;
  if (records.length === 0) return;

  try {
    const res = await fetch(`${relay.replace(/\/llmRelay$/, "")}/saveNarrative`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: credential },
      body: JSON.stringify({
        sessionId: records[0]!.sessionId,
        protocolKey: records[0]!.protocolKey,
        protocolVersion: records[0]!.protocolVersion,
        records,
        finished,
        elapsedSeconds: runStartedAt ? Math.round((Date.now() - runStartedAt) / 1000) : 0,
      }),
    });
    /**
     * Blue ticks mean it is stored, and only that.
     *
     * WhatsApp's blue ticks mean read, and borrowing them for decoration would
     * be a small lie in the one part of the screen that is about whether their
     * words survived. Here they say the run reached the study — which is the
     * honest equivalent, and the thing a participant would actually want to
     * know.
     */
    document.body.classList.toggle("saved", res.ok);
  } catch {
    // Deliberately silent — see above.
  }
}

async function turn(payload: { action: string; input?: string; echo?: boolean }): Promise<void> {
  // Ignore a second click while a call is in flight: double-submitting a turn
  // is how a participant ends up paying for two interviews of themselves.
  if (busy) return;

  /**
   * Their message, on screen the instant they send it.
   *
   * The thread is rebuilt from the records, and the records only come back
   * when the model does — so until now, sending an answer made it disappear
   * for the several seconds the call takes, and the dots appeared where the
   * reply would go. You could watch your own sentence vanish.
   *
   * No messaging app has ever worked that way. The bubble goes up
   * immediately and is replaced by the recorded one when the turn returns,
   * which is the same text: this is the appearance arriving early, not a
   * second copy or an optimistic guess about what will be stored.
   */
  const said = payload.echo === true ? payload.input?.trim() : undefined;
  if (said) {
    $("thread").insertAdjacentHTML("beforeend", bubble("me", escapeHtml(said)));
    scrollThread();
  }

  setBusy(currentKind);
  try {
    if (localRunner) {
      const screen =
        payload.action === "next"
          ? await localRunner.next()
          : payload.action === "skip"
            ? await localRunner.skip()
            : payload.action === "keep"
              ? await localRunner.keepScenario(payload.input ?? "")
              : payload.action === "revert"
                ? localRunner.revertScenario()
                : await localRunner.submit(payload.input ?? "");
      await settle();
      render({ screen, records: localRunner.all, calls: localCalls });
      void store(localRunner, screen.finished);
      return;
    }
    const frame = await api<Frame>("/api/turn", { sessionId, ...payload });
    await settle();
    render(frame);
  } catch (error) {
    // A failed turn must not leave the page disabled and silent.
    $("stageArea").innerHTML =
      `<div class="alert"><strong>Something went wrong:</strong>
       ${escapeHtml(String((error as Error).message ?? error))}.
       Nothing that was written has been lost — it is in the records below.</div>`;
  } finally {
    setBusy(null);
  }
}

