/**
 * The composer is never rebuilt, so it is never rewired.
 *
 * It used to be regenerated with the rest of the stage on every turn. On iOS
 * that destroyed the element the keyboard was attached to: the keyboard closed,
 * the visual viewport grew, `100dvh` recomputed, the frame resized, and then
 * the new box was focused and the whole thing happened in reverse. That is the
 * "small shifts" — the conversation was being measured against a viewport that
 * changed height twice per message.
 */
const composerBar = () => $("composerBar") as HTMLElement;
const messageBox = () => document.getElementById("input") as HTMLTextAreaElement;

/** Height that matches the text, in the same beat WhatsApp's box grows in. */
function sizeMessageBox(): void {
  const box = messageBox();
  /**
   * A hidden box measures zero.
   *
   * `scrollHeight` on a `display: none` element is 0, so sizing the box while
   * the recording strip has it hidden set an inline `height: 0px` that stayed
   * there when the pill came back — and a transcript longer than one line then
   * had nowhere to go. Measuring is only meaningful once it is on screen, so
   * this defers and `showStrip(false)` does it after unhiding.
   */
  if (box.offsetParent === null && box.getClientRects().length === 0) return;
  /**
   * How tall the box may get.
   *
   * Four lines was the old ceiling and it is the wrong one for a spoken
   * answer: somebody who talks says considerably more than somebody who
   * types, and the whole point of showing the transcript is that they can
   * read it and correct it before it is sent. Reading it through a letterbox
   * is not that.
   *
   * Two-fifths of the viewport, which is roughly where WhatsApp's own box
   * stops. Past that it scrolls inside itself rather than pushing the
   * conversation off the screen — the thread has to stay visible, because the
   * question being answered is in it.
   */
  const ceiling = Math.max(120, Math.round(window.innerHeight * 0.4));
  box.style.height = "auto";
  box.style.height = `${Math.min(box.scrollHeight, ceiling)}px`;
  showRightButton();
}

/**
 * The microphone or the send button, never both.
 *
 * WhatsApp swaps one for the other as soon as there is something to send, and
 * two buttons sitting side by side is the tell that this is an imitation. The
 * microphone stays while it is listening, because hiding the control that
 * stops it would be a trap.
 */
function showRightButton(): void {
  const mic = document.getElementById("micBtn") as HTMLButtonElement | null;
  const send = document.getElementById("sendMsg") as HTMLButtonElement | null;
  const empty = messageBox().value.trim().length === 0;
  const listening = mic?.classList.contains("listening") === true;
  // Send hides only when a microphone is there to take its place. A browser
  // with no recogniser would otherwise show an empty box and no button at all.
  const canSpeak = micAvailable();
  if (send) send.hidden = empty && canSpeak && !listening;
  if (mic) mic.hidden = !(canSpeak && (empty || listening));
}
/** Set by `wireMic` once it knows whether this browser can record at all. */
let micSupported = false;
/**
 * A microphone is only offered when there is something behind it: the relay
 * carries the transcriber, so a build without one gets no button rather than a
 * button that fails.
 */
