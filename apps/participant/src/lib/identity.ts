import { db } from "./db.js";
import { ulid } from "./ulid.js";

/**
 * Which iPad this is — decided by the iPad, on first launch, offline.
 *
 * WHY NOT SIGN IN. Three designs have been through here. A researcher pasting a
 * token from a console: a barrier in front of the one thing this exists to do.
 * Anonymous Firebase sign-in: no barrier, but it needs a network to create the
 * identity, and the device that most needs an identity is the one in a school hall
 * with no usable wifi. It also meant a project-level switch somebody had to find,
 * and it put the whole Firebase Auth SDK in a bundle that has to work offline.
 *
 * So the device issues its own credential and does it at first launch: a ULID to
 * be known by, and 32 random bytes to prove it. Both are generated before the app
 * has ever reached the network, which is what makes a device usable from the
 * moment it is unboxed in a hall with no signal.
 *
 * HOW THAT IS STILL TRUSTWORTHY. The secret is registered on first upload —
 * whenever that happens, possibly days later — and from then on the study will
 * only accept that installation id from a caller who can present the same secret.
 * First writer wins, permanently. So a stranger can register a NEW installation
 * (the write endpoint is open by design: anyone with the URL takes part), and
 * cannot ever take over an existing one. That is precisely the property the
 * no-overwrite rule needs: "the same device" has to mean something a second device
 * cannot claim.
 *
 * ITS LIFETIME IS THE DATA'S LIFETIME. Both live in this origin's IndexedDB, next
 * to the AES key the sittings are encrypted with. Clear one and you have cleared
 * all three, so there is no state in which a device holds readable sittings but
 * has forgotten who it is — the state that would have a re-upload refused as a
 * second device claiming the same installation.
 *
 * AND IT TRAVELS WITH A HANDOVER FILE. A device that never reaches the network at
 * all hands its sittings over as a file, and that file carries this installation
 * id — so a sitting that arrives by file and the same sitting arriving later by
 * network are recognised as one sitting from one device, rather than two.
 */

export interface DeviceCredential {
  /** What the study files this device's sittings under. */
  installId: string;
  /** Proof that this is that device. Never leaves the device except to upload. */
  secret: string;
  createdAt: string;
}

export interface DeviceRow extends DeviceCredential {
  id: "install";
}

let cached: DeviceCredential | null = null;

/** 32 bytes, base64url, generated by the device and never derived from anything. */
function freshSecret(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(32));
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

/**
 * This device's credential, creating it the first time it is asked for.
 *
 * Safe to call from anywhere and at any time, including with no network and on the
 * very first launch. Serialised through a single promise so two callers racing at
 * start-up cannot each generate one and leave the device with two identities.
 */
let creating: Promise<DeviceCredential> | null = null;

export function deviceCredential(): Promise<DeviceCredential> {
  if (cached) return Promise.resolve(cached);
  /**
   * A rejected attempt is not remembered.
   *
   * `creating ??= …` alone caches the promise including its rejection, so one transient
   * IndexedDB failure — a locked database during an upgrade, storage momentarily
   * unavailable — would make this reject forever. Everything downstream depends on it:
   * `syncTarget` and `currentDevice` would both fail for the rest of the app's life, and
   * the sync and checkpoint timers would never arm. The device would collect normally and
   * silently never upload, which is the failure mode hardest to notice.
   */
  creating ??= (async () => {
    const existing = await db.install.get("install");
    if (existing) {
      cached = { installId: existing.installId, secret: existing.secret, createdAt: existing.createdAt };
      return cached;
    }
    const made: DeviceCredential = {
      installId: `ipad_${ulid()}`,
      secret: freshSecret(),
      createdAt: new Date().toISOString(),
    };
    /**
     * `add`, not `put`.
     *
     * If another tab won the race between the read above and this write, adding
     * fails on the primary key and the existing credential is read back. Two
     * identities for one device would mean its sittings arriving as if from two
     * iPads and being quarantined against each other.
     */
    try {
      await db.install.add({ id: "install", ...made });
      cached = made;
    } catch {
      const won = await db.install.get("install");
      if (!won) throw new Error("this device could not establish an identity");
      cached = { installId: won.installId, secret: won.secret, createdAt: won.createdAt };
    }
    return cached;
  })().catch((error: unknown) => {
    creating = null;
    throw error;
  });
  return creating;
}

/** The installation id alone, for anything that should not touch the secret. */
export async function installId(): Promise<string> {
  return (await deviceCredential()).installId;
}

/** Only for tests, which need each case to start from an empty device. */
export function forgetCachedCredential(): void {
  cached = null;
  creating = null;
}
